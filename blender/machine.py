class Show:
    """Every ball's position for every frame, plus every mechanism's pose."""

    def __init__(self, m: Machine):
        self.m = m
        self.ts = frame_times()
        self.plan_paths()
        self.plan_balls()

    def plan_paths(self):
        m = self.m
        c, z = m.city_c, m.zc
        y = c.y + m.street_y
        zb = z + R
        # street from slot 0 to the chute
        street = [Vector((c.x + m.slot_x[0] + d, y, zb)) for d in np.linspace(0, 0.2, 10)]
        ch1 = chute_track(m.chute1_axis, m.tray_rc).p
        self.t1 = Track(street + ch1)
        self.d1, self.v1, self.s1 = self.t1.roll(0.85)
        # sorter: ball rolls in from E1 and stops at the centre, then yaw, tilt, roll out
        self.q_in = 0.32
        self.q_yaw = (0.30, 0.52)
        self.q_tilt = (0.50, 0.64)
        self.q_roll0 = 0.58
        self.q_back = (1.12, 1.24)
        self.q_yawback = (1.15, 1.31)
        # roll-out along the tilted tray
        acc = G * math.sin(m.tilt_max)
        self.q_exit = self.q_roll0 + math.sqrt(2 * (m.tray_half) / acc)
        self.v_tray = acc * (self.q_exit - self.q_roll0)
        assert self.q_exit < self.q_back[0], "sorter starts levelling before the ball has left"
        self.t2 = chute_track(m.chute2_axis, m.tray_rc)
        self.d2, self.v2, self.s2 = self.t2.roll(self.v_tray)
        self.tr = chute_track(m.reject_axis, m.tray_rc)
        self.dr, self.vr, self.sr = self.tr.roll(self.v_tray, damping=0.2)
        # chute 2 end to the cart bed: a short hop
        self.hop2 = 0.22
        self.t3 = chute_track(m.chute3_axis, m.tray_rc)
        # arrival times relative to release
        self.A1 = self.d1
        self.Aexit = self.A1 + self.q_exit
        self.C = self.Aexit + self.d2 + self.hop2  # lands on the cart
        print(f"PLAN chute1 {self.d1:.2f}s  sorter exit {self.Aexit:.2f}s  chute2 {self.d2:.2f}s  cart land {self.C:.2f}s")

    # cart and mailbox, relative to the landing time on the cart
    CART = dict(to_writer=(0.15, 0.65), env_out=(0.05, 0.45), fold=(0.45, 0.68), seal=(0.68, 0.78),
                env_slide=(0.78, 1.05), to_dump=(1.5, 2.15), door_open=(1.85, 2.15),
                tip=(2.12, 2.32), untip=(2.95, 3.15), door_close=(3.3, 3.55), flag_up=(3.45, 3.7),
                back=(3.1, 3.7), flag_down=(5.3, 5.6), print=(-0.3, 0.6))

    def plan_balls(self):
        m = self.m
        rng = random.Random(7)
        palette = ["sky", "gold", "lilac", "cream", "sky", "lilac", "ink", "gold", "cream"]
        self.release0 = -0.12
        self.ball_ids = list(range(-9, 9))
        self.colors = {i: ("cardinal" if i == HERO else palette[(i * 5 + 3) % len(palette)]) for i in self.ball_ids}
        self.accepted = {i for i in self.ball_ids if i % ACCEPT_EVERY == 0}
        self.cart_jobs = sorted(self.release0 + i * P + self.C for i in self.accepted)
        # post-cart path, built once with the real door and floor in place
        self.plan_mail_path()
        rng.random()

    def plan_mail_path(self):
        m = self.m
        _, hinge = m.cart_world(m.xD, m.tilt_max if hasattr(m, "tilt_max") else 0)
        tilt = math.radians(32)
        self.bed_tilt = tilt
        _, hinge = m.cart_world(m.xD, tilt)
        edge = hinge @ Vector((0.0, 0, 0.04 + R))
        zf = m.z_floor + R
        door_tip_x = m.mail_front_x - 0.183 * m.mk
        pts = [edge, Vector((edge.x + 0.05, 0, edge.z - 0.012)), Vector((door_tip_x + 0.06, 0, zf + 0.03)),
               Vector((m.mail_front_x, 0, zf + 0.012)), Vector((m.mail_front_x + 0.15, 0, zf)),
               Vector((m.mail_back_x - 0.05, 0, zf)), Vector((m.mail_back_x + 0.03, 0, zf))]
        path = catmull(pts, per_unit=80)
        tail = self.t3.p
        self.tm = Track(path + tail)
        # ball rolls on the tilted bed first
        acc = G * math.sin(tilt)
        bed_len = abs(m.ball_on_bed.x)
        self.bed_roll = math.sqrt(2 * bed_len / acc)
        v_edge = acc * self.bed_roll
        self.dm, self.vm, self.sm = self.tm.roll(v_edge, damping=0.3)
        self.mail_len_in = Track(path).length
        print(f"PLAN bed roll {self.bed_roll:.2f}s  mailbox+chute3 {self.dm:.2f}s")

    # ---- mechanism poses
    def sorter_pose(self, t):
        """(yaw, tilt, verdict) for absolute time t."""
        k = math.floor((t - self.release0 - self.A1) / P)
        i = k
        c = t - (self.release0 + i * P + self.A1)
        target = self.m.yaw_acc if i in self.accepted or i % ACCEPT_EVERY == 0 else self.m.yaw_rej
        yaw = target * (ramp(c, *self.q_yaw) - ramp(c, *self.q_yawback))
        tilt = self.m.tilt_max * (ramp(c, *self.q_tilt) - ramp(c, *self.q_back))
        verdict = (1 if i % ACCEPT_EVERY == 0 else -1) * (ramp(c, 0.25, 0.45) - ramp(c, 1.15, 1.3))
        return yaw, tilt, verdict

    def cart_job(self, t):
        """The cart job active at t: (C, c) with c = t - C, chosen so c spans the whole cycle."""
        best = None
        for C in self.cart_jobs:
            # hand over to the next job only once this one has fully returned
            if t >= C - 0.3:
                best = C
        if best is None:
            best = self.cart_jobs[0]
        return best, t - best

    def cart_pose(self, t):
        m = self.m
        C, c = self.cart_job(t)
        K = self.CART
        x = m.xL
        x += (m.xW - m.xL) * ramp(c, *K["to_writer"])
        x += (m.xD - m.xW) * ramp(c, *K["to_dump"])
        x += (m.xL - m.xD) * ramp(c, *K["back"])
        tilt = self.bed_tilt * (ramp(c, *K["tip"]) - ramp(c, *K["untip"]))
        return x, tilt

    def door_angle(self, t):
        C, c = self.cart_job(t)
        K = self.CART
        return (math.pi / 2) * (ramp(c, *K["door_open"]) - ramp(c, *K["door_close"]))

    def flag_angle(self, t):
        up = 0.0
        for C in self.cart_jobs:
            c = t - C
            a = back_out((c - self.CART["flag_up"][0]) / (self.CART["flag_up"][1] - self.CART["flag_up"][0]), 2.4) if c > self.CART["flag_up"][0] else 0
            a -= ramp(c, *self.CART["flag_down"])
            up = max(up, min(a, 1.4))
        return -math.pi / 2 * (1 - up)

    def gate_angle(self, t):
        u = (t - self.release0) % P
        u = (t - self.release0 + 0.15) % P
        return math.radians(80) * (ramp(u, 0.0, 0.13) - ramp(u, 0.62, 0.78))

    # ---- ball state
    def ball_state(self, i, t):
        """World position and scale for ball i at time t, or None while it is out of play."""
        m = self.m
        rel = self.release0 + i * P
        tau = t - rel
        c, zc = m.city_c, m.zc
        y = c.y + m.street_y
        if tau < -5 * P:
            return None
        if tau < 0:
            # queue in the street: pop up from the manhole, then tick forward a slot per period
            k = int(math.floor(-tau / P))  # slot index currently heading to
            u = tau + (k + 1) * P
            if k >= 4:
                # wait until the ball ahead has rolled clear of the manhole
                s = 0.0 if u < 0.42 else back_out((u - 0.42) / 0.28, 1.8)
                return Vector((c.x + m.slot_x[4], y, zc + R * max(s, 1e-3))), max(s, 0.0)
            frm, to = m.slot_x[k + 1], m.slot_x[k]
            x = frm + (to - frm) * ramp(u, 0.0, 0.4)
            return Vector((c.x + x, y, zc + R)), 1.0
        if tau < self.A1:
            return self.t1.at(sample_lookup(self.s1, tau)), 1.0
        cq = tau - self.A1
        if cq < self.q_exit:
            k = round((rel + self.A1 - self.release0 - self.A1) / P)
            yaw, tilt, _ = self.sorter_pose(t)
            if cq < self.q_in:
                v = self.v1
                u0 = -m.tray_half - 0.02
                x = cq / self.q_in
                # cubic Hermite from (u0, v) to (0, 0)
                h00, h10, h01 = 2 * x ** 3 - 3 * x ** 2 + 1, x ** 3 - 2 * x ** 2 + x, -2 * x ** 3 + 3 * x ** 2
                u = h00 * u0 + h10 * v * self.q_in + h01 * 0.0
            elif cq < self.q_roll0:
                u = 0.0
            else:
                acc = G * math.sin(m.tilt_max)
                u = 0.5 * acc * (cq - self.q_roll0) ** 2
            return m.tray_matrix(yaw, tilt) @ Vector((u, 0, -(m.tray_rc - R))), 1.0
        ce = tau - self.Aexit
        if i % ACCEPT_EVERY != 0:
            if ce < self.dr:
                return self.tr.at(sample_lookup(self.sr, ce)), 1.0
            # off the end of the reject chute: fall into the hole
            cf = ce - self.dr
            p0 = self.tr.p[-1]
            h = m.hole_c
            fall_t = 0.42
            if cf < fall_t:
                u = cf / fall_t
                xy = p0.lerp(Vector((h.x, h.y, 0)), min(1.0, u * 1.6))
                zz = p0.z - 0.5 * G * 1.4 * cf * cf
                return Vector((xy.x, xy.y, zz)), 1.0
            return None
        if ce < self.d2:
            return self.t2.at(sample_lookup(self.s2, ce)), 1.0
        ch = ce - self.d2
        C = rel + self.C
        if ch < self.hop2:
            p0 = self.t2.p[-1]
            x, tilt = self.cart_pose(t)
            _, hinge = m.cart_world(x, tilt)
            p1 = hinge @ m.ball_on_bed
            u = ch / self.hop2
            p = p0.lerp(p1, smooth(u))
            p.z = p0.z + (p1.z - p0.z) * u * u
            return p, 1.0
        c = t - C
        roll0 = self.CART["tip"][0] + 0.12
        if c < roll0:
            x, tilt = self.cart_pose(t)
            _, hinge = m.cart_world(x, tilt)
            return hinge @ m.ball_on_bed, 1.0
        cb = c - roll0
        if cb < self.bed_roll:
            x, tilt = self.cart_pose(t)
            _, hinge = m.cart_world(x, tilt)
            acc = G * math.sin(self.bed_tilt)
            u = m.ball_on_bed.x + 0.5 * acc * cb * cb
            return hinge @ Vector((u, 0, m.ball_on_bed.z)), 1.0
        cm = cb - self.bed_roll
        if cm < self.dm:
            return self.tm.at(sample_lookup(self.sm, cm)), 1.0
        # fly from chute 3 onto the stack, bounce once, then become a block
        cf = cm - self.dm
        p0 = self.tm.p[-1]
        land_t = rel + self.C + roll0 + self.bed_roll + self.dm
        top = self.slab_top(i)
        land = Vector((m.stack_c.x, m.stack_c.y, top + R))
        fl = self.flight_time(p0, land)
        if cf < fl:
            u = cf / fl
            p = p0.lerp(land, u)
            p.z = p0.z + (land.z - p0.z) * u + 0.5 * G * cf * (fl - cf) * (1 - u * 0.0) * 0.0 + self.arc(p0, land, fl, cf)
            return p, 1.0
        cs = cf - fl
        g0 = self.grow_start(i)
        if t < g0:
            bounce = 0.05 * max(0.0, math.sin(math.pi * min(cs / 0.2, 1.0)))
            return land + Vector((0, 0, bounce)), 1.0
        gu = (t - g0) / 0.38
        if gu >= 1:
            return None
        grow = back_out(gu, 1.4)
        s = 1.0 - smooth(gu * 1.15)
        return Vector((land.x, land.y, top + m.slab_h * grow + R * max(s, 0))), max(s, 0.0)

    def arc(self, p0, p1, fl, cf):
        # ballistic arc on top of the straight-line interpolation
        lin = p0.z + (p1.z - p0.z) * (cf / fl)
        z = p0.z + ((p1.z - p0.z) + 0.5 * G * fl * fl) / fl * cf - 0.5 * G * cf * cf
        return z - lin

    def flight_time(self, p0, p1):
        # fall height plus a little hop; fixed small arc speed
        dz = p0.z - p1.z
        return math.sqrt(2 * max(dz, 0.02) / G) + 0.08

    def land_time(self, i):
        rel = self.release0 + i * P
        roll0 = self.CART["tip"][0] + 0.12
        return rel + self.C + roll0 + self.bed_roll + self.dm

    def grow_start(self, i):
        lt = self.land_time(i)
        p0 = self.tm.p[-1]
        top = self.slab_top(i)
        return lt + self.flight_time(p0, Vector((0, 0, top + R))) + 0.3

    def stage_times(self):
        """Scene-time windows for the page captions, all from the hero's own timeline."""
        rel = self.release0 + HERO * P
        C = rel + self.C
        K = self.CART
        grow_end = self.grow_start(HERO) + 0.45
        t_end = T0 + (FRAMES - 1) / FPS
        assert t_end - grow_end > 1.3, f"pull-back too short: {t_end - grow_end:.2f}s"
        return {
            "tray": (T0 + 0.45, rel + 0.2),
            "sort": (rel + 0.2, C - 0.1),
            "type": (C - 0.1, C + K["to_dump"][0]),
            "mail": (C + K["to_dump"][0], C + K["flag_up"][1] + 0.25),
            "stack": (C + K["flag_up"][1] + 0.25, grow_end),
            "out": (grow_end, t_end),
        }

    def stage_frames(self):
        return {k: [int(round((a - T0) * FPS)) + 1, int(round((b - T0) * FPS)) + 1]
                for k, (a, b) in self.stage_times().items()}

    def slab_top(self, i):
        """Top of the stack the moment accepted ball i lands: every earlier
        accepted ball has long since become its own slab."""
        rank = sorted(self.accepted).index(i)
        return 0.06 + (self.base_slabs + rank) * self.m.slab_h


