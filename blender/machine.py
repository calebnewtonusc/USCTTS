def srgb_to_lin(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def hexcol(h):
    h = HEX.get(h, h)
    return tuple(srgb_to_lin(int(h[i:i + 2], 16) / 255) for i in (0, 2, 4)) + (1.0,)


# ---------------------------------------------------------------- utilities

def smooth(x):
    x = min(max(x, 0.0), 1.0)
    return x * x * (3 - 2 * x)


def smoother(x):
    x = min(max(x, 0.0), 1.0)
    return x * x * x * (x * (6 * x - 15) + 10)


def ramp(t, t0, t1):
    return smoother((t - t0) / (t1 - t0)) if t1 > t0 else float(t >= t1)


def back_out(x, s=1.6):
    x = min(max(x, 0.0), 1.0)
    x -= 1
    return x * x * ((s + 1) * x + s) + 1


def link(obj, coll=None):
    (coll or bpy.context.scene.collection).objects.link(obj)
    return obj


def new_mesh_obj(name, bm, mat=None, smooth_shade=True):
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    if smooth_shade:
        me.shade_smooth()
    ob = bpy.data.objects.new(name, me)
    if mat:
        me.materials.append(mat)
    return link(ob)


def rounded_box(name, size, mat, bevel=0.03, location=(0, 0, 0), subdiv=1, wobble=0.0):
    bm = bmesh.new()
    bmesh.ops.create_cube(bm, size=1.0)
    for v in bm.verts:
        v.co = Vector((v.co.x * size[0], v.co.y * size[1], v.co.z * size[2]))
    ob = new_mesh_obj(name, bm, mat)
    ob.location = location
    m = ob.modifiers.new("bevel", "BEVEL")
    m.width = min(bevel, min(size) * 0.49)
    m.segments = 4
    m.limit_method = "NONE"
    if subdiv:
        s = ob.modifiers.new("subd", "SUBSURF")
        s.levels = s.render_levels = subdiv
    if wobble:
        add_wobble(ob, wobble)
    return ob


def cylinder(name, radius, depth, mat, location=(0, 0, 0), segments=48, bevel=0.015, axis="Z"):
    bm = bmesh.new()
    bmesh.ops.create_cone(bm, cap_ends=True, cap_tris=False, segments=segments,
                          radius1=radius, radius2=radius, depth=depth)
    if axis == "X":
        bmesh.ops.rotate(bm, verts=bm.verts, cent=(0, 0, 0), matrix=Matrix.Rotation(math.pi / 2, 3, "Y"))
    elif axis == "Y":
        bmesh.ops.rotate(bm, verts=bm.verts, cent=(0, 0, 0), matrix=Matrix.Rotation(math.pi / 2, 3, "X"))
    ob = new_mesh_obj(name, bm, mat)
    ob.location = location
    if bevel:
        m = ob.modifiers.new("bevel", "BEVEL")
        m.width = min(bevel, radius * 0.45, depth * 0.45)
        m.segments = 4
        m.limit_method = "ANGLE"
    return ob


def sphere(name, radius, mat, location=(0, 0, 0)):
    bm = bmesh.new()
    bmesh.ops.create_uvsphere(bm, u_segments=48, v_segments=24, radius=radius)
    ob = new_mesh_obj(name, bm, mat)
    ob.location = location
    return ob


_wobble_tex = None


def add_wobble(ob, strength):
    """Low-frequency displacement: hand-made, not machined."""
    global _wobble_tex
    if _wobble_tex is None:
        _wobble_tex = bpy.data.textures.new("wobble", "CLOUDS")
        _wobble_tex.noise_scale = 0.35
    d = ob.modifiers.new("wobble", "DISPLACE")
    d.texture = _wobble_tex
    d.strength = strength
    d.mid_level = 0.5
    d.texture_coords = "GLOBAL"


