def append_part(fname):
    path = os.path.join(PARTS, fname)
    with bpy.data.libraries.load(path, link=False) as (src, dst):
        dst.objects = src.objects
    coll = bpy.data.collections.new(fname.replace(".blend", ""))
    bpy.context.scene.collection.children.link(coll)
    objs = [o for o in dst.objects if o is not None]
    for o in objs:
        coll.objects.link(o)
        reskin(o)
        for m in o.modifiers:
            if m.type == "BEVEL" and getattr(m, "harden_normals", False):
                m.harden_normals = False
    return objs


def by_name(objs, name):
    """Appended names gain .001 suffixes when another part used the name first."""
    for o in objs:
        if o.name == name or re.fullmatch(re.escape(name) + r"\.\d{3}", o.name):
            return o
    raise SystemExit(f"part object {name!r} not found")


def root_of(objs, name_contains):
    for o in objs:
        if name_contains in o.name and o.parent is None:
            return o
    for o in objs:
        if name_contains in o.name:
            return o
    raise SystemExit(f"part root {name_contains!r} not found")


def place(root, location, scale, rot_z=0.0):
    holder = bpy.data.objects.new(root.name + "_place", None)
    link(holder, root.users_collection[0])
    holder.location = location
    holder.rotation_euler = (0, 0, rot_z)
    holder.scale = (scale,) * 3
    root.parent = holder
    return holder


def descendants(ob):
    out = []
    for c in ob.children:
        out.append(c)
        out += descendants(c)
    return out


def world_bbox(objs):
    pts = []
    for o in objs:
        if o.type == "MESH":
            pts += [o.matrix_world @ Vector(c) for c in o.bound_box]
    mn = Vector([min(p[i] for p in pts) for i in range(3)])
    mx = Vector([max(p[i] for p in pts) for i in range(3)])
    return mn, mx


