def build_and_bake():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    random.seed(3)
    m = Machine()
    show = Show(m)
    ts = show.ts
    # stack: decide base so the stack shows 4 slabs at frame 1
    show.base_slabs = 2

    # balls
    mats = {}
    ball_objs = {}
    for i in show.ball_ids:
        ob = sphere(f"Ball_{i:+d}", R, clay(show.colors[i], rough=0.45))
        add_wobble(ob, 0.0015)
        ball_objs[i] = ob
    positions = {i: [] for i in show.ball_ids}
    for i, ob in ball_objs.items():
        rot = Quaternion()
        prev = None
        mats_i = []
        for t in ts:
            st = show.ball_state(i, t)
            if st is None:
                pos, s = Vector((0, 0, -5)), 0.0
            else:
                pos, s = st
            if prev is not None and st is not None:
                d = pos - prev
                d.z = 0 if abs(d.z) < 1e-6 else d.z
                if d.length > 1e-6:
                    axis = Vector((0, 0, 1)).cross(d)
                    if axis.length > 1e-6:
                        rot = Quaternion(axis.normalized(), d.length / R) @ rot
            prev = pos if st is not None else None
            positions[i].append(None if st is None else (pos.copy(), s))
            mats_i.append(Matrix.LocRotScale(pos, rot, Vector((max(s, 0.0),) * 3)))
        bake_matrices(ob, mats_i)
    show.positions = positions
    show.ball_objs = ball_objs

    # sorter
    yaws, tilts, needles = [], [], []
    for t in ts:
        yaw, tilt, verdict = show.sorter_pose(t)
        yaws.append(yaw)
        tilts.append(tilt)
        needles.append(verdict * 0.7)
    fcurve_bake(m.sorter_yaw, "rotation_euler", [[0] * len(ts), [0] * len(ts), yaws])
    fcurve_bake(m.sorter_tilt, "rotation_euler", [[0] * len(ts), tilts, [0] * len(ts)])
    fcurve_bake(m.needle, "rotation_euler", [[0] * len(ts), needles, [0] * len(ts)])
    # gate
    fcurve_bake(m.gate, "rotation_euler", [[0] * len(ts), [-show.gate_angle(t) for t in ts], [0] * len(ts)])
    # cart
    xs, bed = [], []
    for t in ts:
        x, tilt = show.cart_pose(t)
        xs.append(x)
        bed.append(tilt)
    fcurve_bake(m.cart, "location", [xs, [0] * len(ts), [m.zd] * len(ts)])
    fcurve_bake(m.bed_hinge, "rotation_euler", [[0] * len(ts), bed, [0] * len(ts)])
    for w in m.wheels:
        w.rotation_mode = "XYZ"
        fcurve_bake(w, "rotation_euler", [[0] * len(ts), [(x - m.xL) / 0.065 for x in xs], [0] * len(ts)])
    # mailbox door and flag (Nalana's door opens about its local X; 0 is closed)
    fcurve_bake(m.door, "rotation_euler", [[show.door_angle(t) for t in ts], [0] * len(ts), [0] * len(ts)])
    fcurve_bake(m.flag, "rotation_euler", [[show.flag_angle(t) for t in ts], [0] * len(ts), [0] * len(ts)])
    # print head shuttles while a letter is being written
    ph = m.printhead
    rest = m.printhead_rest
    hx = []
    for t in ts:
        C, c = show.cart_job(t)
        a, b = show.CART["print"]
        on = ramp(c, a, a + 0.15) - ramp(c, b - 0.15, b)
        hx.append(rest.x + on * 0.09 * math.sin(2 * math.pi * 2.2 * (c - a)))
    fcurve_bake(ph, "location", [hx, [rest.y] * len(ts), [rest.z] * len(ts)])

    build_envelopes(m, show)
    build_stack(m, show)
    return m, show


def build_envelopes(m, show):
    env_mat = clay("cream", rough=0.7)
    flap_mat = clay("creamdeep", rough=0.7)
    ts = show.ts
    K = show.CART
    for n, C in enumerate(show.cart_jobs):
        if C + 3.4 < 0 or C - 1 > ts[-1]:
            continue
        root = bpy.data.objects.new(f"Envelope_{n}", None)
        link(root)
        body = rounded_box(f"EnvBody_{n}", (0.22, 0.15, 0.014), env_mat, bevel=0.005, location=(0, 0, 0.007), subdiv=0)
        body.parent = root
        hinge = bpy.data.objects.new(f"EnvHinge_{n}", None)
        link(hinge)
        hinge.parent = root
        hinge.location = (0, 0.075, 0.014)
        bm = bmesh.new()
        vs = [bm.verts.new(v) for v in [(-0.108, 0, 0), (0.108, 0, 0), (0, -0.09, 0)]]
        bm.faces.new(vs)
        bmesh.ops.solidify(bm, geom=bm.faces[:], thickness=0.004)
        flap = new_mesh_obj(f"EnvFlap_{n}", bm, flap_mat)
        flap.parent = hinge
        seal = cylinder(f"EnvSeal_{n}", 0.022, 0.006, clay("cardinal" if n == show.cart_jobs.index(min(show.cart_jobs, key=lambda c: abs(c - (show.release0 + HERO * P + show.C)))) else "gold"),
                        location=(0, 0.015, 0.02), bevel=0.002)
        seal.parent = root
        mats, flaps, seals = [], [], []
        ledge = m.ledge
        roll0 = K["tip"][0] + 0.06
        for t in ts:
            c = t - C
            yaw = Matrix.Rotation(0, 4, "Z")
            if c < K["env_out"][0] or c > K["tip"][0] + 0.9:
                mats.append(Matrix.LocRotScale(Vector((0, 0.6, m.writer_z + 0.1)), None, Vector((0, 0, 0))))
            elif c < K["env_slide"][0]:
                u = ramp(c, *K["env_out"])
                p = Vector((0, ledge.y + 0.16 * (1 - u), ledge.z))
                mats.append(Matrix.Translation(p))
            elif c < K["env_slide"][1]:
                u = ramp(c, *K["env_slide"])
                x, tilt = show.cart_pose(t)
                _, h = m.cart_world(x, tilt)
                target = h @ Matrix.Translation(m.env_on_bed)
                p0 = Matrix.Translation(ledge)
                p = p0.to_translation().lerp(target.to_translation(), u)
                p.z += 0.04 * math.sin(math.pi * u)
                mats.append(Matrix.Translation(p))
            else:
                x, tilt = show.cart_pose(t)
                _, h = m.cart_world(x, tilt)
                if c < roll0:
                    mats.append(h @ Matrix.Translation(m.env_on_bed))
                else:
                    cb = c - roll0
                    acc = G * math.sin(show.bed_tilt) * 0.8
                    u = m.env_on_bed.x + 0.5 * acc * cb * cb
                    if u < 0.1:
                        mats.append(h @ Matrix.Translation((u, 0, m.env_on_bed.z)))
                    else:
                        # off the bed: slide across the door into the mailbox, then gone
                        edge = h @ Vector((0.1, 0, m.env_on_bed.z))
                        d = (u - 0.1)
                        p = Vector((edge.x + d, 0, max(m.z_floor + 0.002, edge.z - d * 0.5)))
                        if p.x > m.mail_front_x + 0.2:
                            mats.append(Matrix.LocRotScale(p, None, Vector((0, 0, 0))))
                        else:
                            mats.append(Matrix.Translation(p))
            flaps.append(math.radians(165) * (1 - ramp(c, *K["fold"])))
            seals.append(back_out((c - K["seal"][0]) / 0.12, 2.0) if c > K["seal"][0] else 0.0)
        bake_matrices(root, mats)
        fcurve_bake(hinge, "rotation_euler", [[-a for a in flaps], [0] * len(ts), [0] * len(ts)])
        fcurve_bake(seal, "scale", [seals, seals, seals])


def build_stack(m, show):
    ts = show.ts
    cols = ["cream", "gold"]
    s = m.stack_c
    rng = random.Random(11)
    n_static = show.base_slabs
    slabs = []
    for k in range(n_static):
        slabs.append((k, None))
    growers = sorted(show.accepted)  # one slab per accepted ball, in order
    for j in growers:
        slabs.append((None, j))
    level = 0
    show.slab_objs = []
    for idx, (k, j) in enumerate(slabs):
        col = cols[idx % 2]
        ob = rounded_box(f"Slab_{idx}", (m.slab_w, m.slab_w, m.slab_h - 0.006), clay(col), bevel=0.035,
                         location=(0, 0, 0), wobble=0.003)
        dotcol = show.colors[j] if j is not None else rng.choice(["sky", "lilac", "cardinal", "gold", "cream"])
        if dotcol == col:
            dotcol = "sky"
        dot = cylinder(f"SlabDot_{idx}", 0.045, 0.02, clay(dotcol), location=(0, -m.slab_w / 2 - 0.004, 0), axis="Y", bevel=0.006)
        dot.parent = ob
        jit = rng.uniform(-0.07, 0.07)
        z0 = 0.06 + idx * m.slab_h + (m.slab_h - 0.006) / 2
        mats = []
        for t in ts:
            if j is None:
                sc_ = 1.0
            else:
                g0 = show.grow_start(j)
                sc_ = back_out((t - g0) / 0.38, 1.4) if t > g0 else 0.0
            zz = 0.06 + idx * m.slab_h + (m.slab_h - 0.006) / 2 * max(sc_, 1e-3)
            mats.append(Matrix.LocRotScale(Vector((s.x, s.y, zz)), Quaternion((0, 0, 1), jit),
                                           Vector((1.0 if sc_ > 0 else 0, 1.0 if sc_ > 0 else 0, max(sc_, 0.0)))))
        bake_matrices(ob, mats)
        m.collide(ob, animated=True)
        show.slab_objs.append((ob, j))


