def light_rig(**over):
    """One big soft key, high and in front and to one side, plus a warm
    gradient environment that lifts every shadow to a warm grey-brown.
    Matched against Clay's Orch loop in blender/lookdev.py."""
    cfg = dict(LIGHT_V2 if LOOK["name"] == "v2" else LIGHT, **over)
    sc = bpy.context.scene
    sun = bpy.data.objects.new("Key", bpy.data.lights.new("Key", "SUN"))
    sun.data.energy = cfg["key_energy"]
    sun.data.angle = math.radians(cfg["key_angle"])
    sun.data.color = (1.0, 0.99, 0.975)
    sun.rotation_euler = (math.radians(90 - cfg["key_elev"]), 0, math.radians(cfg["key_az"]))
    link(sun)
    w = bpy.data.worlds.new("World")
    sc.world = w
    w.use_nodes = True
    nt = w.node_tree
    bg = next(n for n in nt.nodes if n.type == "BACKGROUND")
    bg.inputs["Strength"].default_value = cfg["world_strength"]
    # vertical gradient: bright warm white at the horizon, a touch deeper overhead
    geo = nt.nodes.new("ShaderNodeNewGeometry")
    sep = nt.nodes.new("ShaderNodeSeparateXYZ")
    nt.links.new(geo.outputs["Incoming"], sep.inputs["Vector"])
    cr = nt.nodes.new("ShaderNodeValToRGB")
    cr.color_ramp.elements[0].position = 0.0
    cr.color_ramp.elements[0].color = hexcol(cfg["horizon"])
    cr.color_ramp.elements[1].position = 0.45
    cr.color_ramp.elements[1].color = hexcol(cfg["zenith"])
    absz = nt.nodes.new("ShaderNodeMath")
    absz.operation = "ABSOLUTE"
    nt.links.new(sep.outputs["Z"], absz.inputs[0])
    nt.links.new(absz.outputs[0], cr.inputs["Fac"])
    nt.links.new(cr.outputs["Color"], bg.inputs["Color"])
    # the camera sees a brighter backdrop than the one that lights the set,
    # the way a studio sweep reads lighter than the fill it bounces
    lp = nt.nodes.new("ShaderNodeLightPath")
    bright = nt.nodes.new("ShaderNodeBackground")
    bright.inputs["Strength"].default_value = cfg["world_strength"] * cfg["camera_bg"]
    nt.links.new(cr.outputs["Color"], bright.inputs["Color"])
    mixs = nt.nodes.new("ShaderNodeMixShader")
    nt.links.new(lp.outputs["Is Camera Ray"], mixs.inputs[0])
    nt.links.new(bg.outputs[0], mixs.inputs[1])
    nt.links.new(bright.outputs[0], mixs.inputs[2])
    wout = next(n for n in nt.nodes if n.type == "OUTPUT_WORLD")
    nt.links.new(mixs.outputs[0], wout.inputs["Surface"])
    _VIEW.update(exposure=cfg["exposure"], look=cfg["look"], view=cfg["view"])
    return sun


