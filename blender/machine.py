def fcurve_bake(id_data, path, per_index_values, start=1):
    """Write one keyframe per frame, linear, through the slotted-action API."""
    ad = id_data.animation_data_create()
    if ad.action is None:
        act = bpy.data.actions.new(f"{id_data.name}_act")
        ad.action = act
        if ad.action_slot is None:
            slot = act.slots.new(id_type=id_data.id_type, name=id_data.name)
            ad.action_slot = slot
    cb = anim_utils.action_ensure_channelbag_for_slot(ad.action, ad.action_slot)
    for idx, values in enumerate(per_index_values):
        fc = cb.fcurves.find(path, index=idx) or cb.fcurves.new(path, index=idx)
        n = len(values)
        fc.keyframe_points.clear()
        fc.keyframe_points.add(n)
        co = []
        for k, v in enumerate(values):
            co += [start + k, v]
        fc.keyframe_points.foreach_set("co", co)
        fc.keyframe_points.foreach_set("interpolation", [1] * n)  # LINEAR
        fc.update()


def bake_matrices(ob, mats):
    """mats: world (or parent-space) matrices per frame."""
    locs, rots, scs = [[], [], []], [[], [], [], []], [[], [], []]
    ob.rotation_mode = "QUATERNION"
    prev = None
    for m in mats:
        l, q, s = m.decompose()
        if prev is not None and prev.dot(q) < 0:
            q = -q
        prev = q
        for i in range(3):
            locs[i].append(l[i])
            scs[i].append(s[i])
        for i in range(4):
            rots[i].append(q[i])
    fcurve_bake(ob, "location", locs)
    fcurve_bake(ob, "rotation_quaternion", rots)
    fcurve_bake(ob, "scale", scs)


def frame_times():
    return [T0 + (f - 1) / FPS for f in range(1, FRAMES + 1)]


