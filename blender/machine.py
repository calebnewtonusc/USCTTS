def catmull(points, per_unit=60):
    pts = [Vector(p) for p in points]
    out = []
    ext = [pts[0] * 2 - pts[1]] + pts + [pts[-1] * 2 - pts[-2]]
    for i in range(1, len(ext) - 2):
        p0, p1, p2, p3 = ext[i - 1], ext[i], ext[i + 1], ext[i + 2]
        n = max(4, int((p2 - p1).length * per_unit))
        for k in range(n):
            t = k / n
            t2, t3 = t * t, t * t * t
            out.append(0.5 * ((2 * p1) + (-p0 + p2) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t2
                              + (-p0 + 3 * p1 - 3 * p2 + p3) * t3))
    out.append(pts[-1])
    return out


def helix(center, radius, z0, z1, a0, turns, n=240):
    out = []
    for k in range(n + 1):
        u = k / n
        a = a0 - 2 * math.pi * turns * u  # clockwise seen from above
        out.append(Vector((center[0] + radius * math.cos(a), center[1] + radius * math.sin(a), z0 + (z1 - z0) * u)))
    return out


def smooth_polyline(pts, window):
    """Moving-average the interior so joins between straight runs and the helix
    lose their crease; both ends stay exactly where they were."""
    out = [p.copy() for p in pts]
    h = window // 2
    for i in range(h, len(pts) - h):
        acc = Vector((0, 0, 0))
        for k in range(i - h, i + h + 1):
            acc += pts[k]
        out[i] = acc / window
    return out


def frames_along(axis):
    tangents, ups = [], []
    for i in range(len(axis)):
        a = axis[max(i - 1, 0)]
        b = axis[min(i + 1, len(axis) - 1)]
        t = (b - a).normalized()
        up = Vector((0, 0, 1)) - t * t.z
        tangents.append(t)
        ups.append(up.normalized())
    return tangents, ups


def strut_under(name, axis, frac, mat, floor=0.0, rc=0.14, wall=0.035):
    p = axis[int(frac * (len(axis) - 1))]
    top = p.z - rc - wall - 0.04
    return cylinder(name, 0.02, top - floor, mat, location=(p.x, p.y, floor + (top - floor) / 2))


def make_chute(name, axis, rc=0.14, wall=0.035, lip_deg=28, mat=None):
    """A half-pipe swept along the axis polyline; the lips rise past horizontal."""
    tangents, ups = frames_along(axis)
    prof = []
    a0, a1 = math.radians(-180 - lip_deg), math.radians(lip_deg)
    n = 28
    for k in range(n + 1):
        a = a0 + (a1 - a0) * k / n
        prof.append((rc * math.cos(a), rc * math.sin(a)))
    for k in range(1, 8):  # rounded lip
        a = a1 + math.pi * k / 8
        c = ((rc + wall / 2) * math.cos(a1), (rc + wall / 2) * math.sin(a1))
        prof.append((c[0] + wall / 2 * math.cos(a), c[1] + wall / 2 * math.sin(a)))
    for k in range(n, -1, -1):
        a = a0 + (a1 - a0) * k / n
        prof.append(((rc + wall) * math.cos(a), (rc + wall) * math.sin(a)))
    for k in range(1, 8):
        a = a0 + math.pi + math.pi * k / 8
        c = ((rc + wall / 2) * math.cos(a0), (rc + wall / 2) * math.sin(a0))
        prof.append((c[0] + wall / 2 * math.cos(a), c[1] + wall / 2 * math.sin(a)))
    bm = bmesh.new()
    rings = []
    for p, t, up in zip(axis, tangents, ups):
        side = t.cross(up).normalized()
        rings.append([bm.verts.new(p + side * x + up * y) for x, y in prof])
    m = len(prof)
    for i in range(len(rings) - 1):
        for k in range(m):
            bm.faces.new((rings[i][k], rings[i][(k + 1) % m], rings[i + 1][(k + 1) % m], rings[i + 1][k]))
    bm.normal_update()
    ob = new_mesh_obj(name, bm, mat or clay("cream"))
    return ob


class Track:
    """Ball-centre path for a ball riding the bottom of a half-pipe or a floor."""

    def __init__(self, centers):
        self.p = [Vector(c) for c in centers]
        self.s = [0.0]
        for a, b in zip(self.p, self.p[1:]):
            self.s.append(self.s[-1] + (b - a).length)
        self.length = self.s[-1]

    def at(self, s):
        s = min(max(s, 0.0), self.length)
        lo, hi = 0, len(self.s) - 1
        while hi - lo > 1:
            mid = (lo + hi) // 2
            if self.s[mid] <= s:
                lo = mid
            else:
                hi = mid
        seg = self.s[hi] - self.s[lo]
        u = 0.0 if seg == 0 else (s - self.s[lo]) / seg
        return self.p[lo].lerp(self.p[hi], u)

    def slope(self, s):
        a, b = self.at(s - 0.01), self.at(s + 0.01)
        d = (b - a).length
        return 0.0 if d == 0 else (b.z - a.z) / d

    def roll(self, v0, damping=0.25, vmin=1.25, vmax=4.5):
        """Integrate gravity along the track. Returns (duration, v_end, samples[(t, s)])."""
        dt = 1 / 1200
        t, s, v = 0.0, 0.0, max(v0, vmin)
        samples = [(0.0, 0.0)]
        while s < self.length:
            a = -G * self.slope(s) - damping * v
            v = min(max(v + a * dt, vmin), vmax)
            s += v * dt
            t += dt
            samples.append((t, min(s, self.length)))
        return t, v, samples


def chute_track(axis, rc=0.14):
    tangents, ups = frames_along(axis)
    # the ball rides 8 mm proud of the trough: the swept rings pinch slightly on
    # tight bends, and the audit caught 9 mm overlaps on chute 3 without this
    return Track([p - u * (rc - R - 0.008) for p, u in zip(axis, ups)])


def sample_lookup(samples, t):
    lo, hi = 0, len(samples) - 1
    if t <= 0:
        return samples[0][1]
    if t >= samples[-1][0]:
        return samples[-1][1]
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if samples[mid][0] <= t:
            lo = mid
        else:
            hi = mid
    (t0, s0), (t1, s1) = samples[lo], samples[hi]
    return s0 + (s1 - s0) * (t - t0) / (t1 - t0)


