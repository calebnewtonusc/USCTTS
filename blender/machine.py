def audit(m, show, every=1):
    """Fail loudly if any ball ever overlaps geometry or another ball, or teleports."""
    sc = bpy.context.scene
    tol = 0.006
    statics, animated = [], []
    dg = bpy.context.evaluated_depsgraph_get()
    for ob, anim in m.colliders:
        if ob.type != "MESH":
            continue
        (animated if anim else statics).append(ob)
    def tree(ob):
        ev = ob.evaluated_get(dg)
        me = ev.to_mesh()
        bm = bmesh.new()
        bm.from_mesh(me)
        ev.to_mesh_clear()
        if not bm.faces:
            return None
        return BVHTree.FromBMesh(bm)
    sc.frame_set(1)
    dg = bpy.context.evaluated_depsgraph_get()
    static_trees = [(ob, tree(ob), ob.matrix_world.copy()) for ob in statics]
    static_trees = [s for s in static_trees if s[1] is not None]
    problems = []
    for f in range(1, FRAMES + 1, every):
        sc.frame_set(f)
        dg = bpy.context.evaluated_depsgraph_get()
        anim_trees = []
        for ob in animated:
            mw = ob.matrix_world.copy()
            if abs(mw.determinant()) < 1e-9:
                continue
            tr = tree(ob)
            if tr:
                anim_trees.append((ob, tr, mw))
        live = []
        for i in show.ball_ids:
            st = show.positions[i][f - 1]
            if st is None or st[1] < 0.98:
                continue
            p = st[0]
            if p.z < 0.0:
                continue
            live.append((i, p))
            for ob, tr, mw in static_trees + anim_trees:
                inv = mw.inverted()
                q = inv @ p
                hit = tr.find_nearest(q, R * 3)
                if hit[0] is None:
                    continue
                w = mw @ hit[0]
                d = (w - p).length
                if d < R - tol:
                    problems.append(f"frame {f}: ball {i:+d} at {tuple(round(v, 3) for v in p)} is {R - d:.3f} inside {ob.name}")
        for a in range(len(live)):
            for b in range(a + 1, len(live)):
                d = (live[a][1] - live[b][1]).length
                if d < 2 * R - tol:
                    problems.append(f"frame {f}: balls {live[a][0]:+d} and {live[b][0]:+d} overlap by {2 * R - d:.3f}")
    for i in show.ball_ids:
        seq = show.positions[i]
        for f in range(1, len(seq)):
            if seq[f] and seq[f - 1] and seq[f][1] > 0.98 and seq[f - 1][1] > 0.98:
                jump = (seq[f][0] - seq[f - 1][0]).length
                if jump > 0.25:
                    problems.append(f"frame {f + 1}: ball {i:+d} jumps {jump:.2f} in one frame")
    if problems:
        print("AUDIT FAILED", len(problems))
        seen = {}
        for p in problems:
            key = p.split(" is ")[-1].split(" inside ")[-1] if " inside " in p else p
            seen.setdefault(key, []).append(p)
        for key, ps in list(seen.items())[:40]:
            print("  ", ps[0], f"(+{len(ps) - 1} more like it)")
        raise SystemExit(2)
    print("AUDIT OK: no ball touches geometry, no overlaps, no jumps across", FRAMES, "frames")


