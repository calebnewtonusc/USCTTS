def clay(key, color=None, rough=0.58, bump=1.0):
    """Matte clay: soft sheen, fine grain bump, a slow lumpy bump, tiny value drift."""
    name = f"clay_{key}_{LOOK['name']}"
    if name in _mats:
        return _mats[name]
    col = hexcol(key) if color is None else color
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    out = nt.nodes.new("ShaderNodeOutputMaterial")
    bsdf = nt.nodes.new("ShaderNodeBsdfPrincipled")
    bsdf.inputs["Roughness"].default_value = rough
    bsdf.inputs["Specular IOR Level"].default_value = 0.32
    bsdf.inputs["Sheen Weight"].default_value = 0.12
    bsdf.inputs["Sheen Roughness"].default_value = 0.6
    bsdf.inputs["Subsurface Weight"].default_value = 0.04
    bsdf.inputs["Subsurface Radius"].default_value = (1.0, 0.55, 0.35)
    bsdf.inputs["Subsurface Scale"].default_value = 0.004
    tc = nt.nodes.new("ShaderNodeTexCoord")
    fine = nt.nodes.new("ShaderNodeTexNoise")
    fine.inputs["Scale"].default_value = 140.0
    fine.inputs["Detail"].default_value = 3.0
    lump = nt.nodes.new("ShaderNodeTexNoise")
    lump.inputs["Scale"].default_value = 7.0
    lump.inputs["Detail"].default_value = 2.0
    nt.links.new(tc.outputs["Object"], fine.inputs["Vector"])
    nt.links.new(tc.outputs["Object"], lump.inputs["Vector"])
    b1 = nt.nodes.new("ShaderNodeBump")
    b1.inputs["Strength"].default_value = 0.10 * bump
    b1.inputs["Distance"].default_value = 0.002
    b2 = nt.nodes.new("ShaderNodeBump")
    b2.inputs["Strength"].default_value = 0.06 * bump
    b2.inputs["Distance"].default_value = 0.02
    nt.links.new(fine.outputs["Fac"], b1.inputs["Height"])
    nt.links.new(lump.outputs["Fac"], b2.inputs["Height"])
    nt.links.new(b1.outputs["Normal"], b2.inputs["Normal"])
    nt.links.new(b2.outputs["Normal"], bsdf.inputs["Normal"])
    # value drift of about 3%, so large faces do not read as flat CG fills
    mix = nt.nodes.new("ShaderNodeMix")
    mix.data_type = "RGBA"
    mix.blend_type = "MULTIPLY"
    mix.inputs["Factor"].default_value = 1.0
    mix.inputs[6].default_value = col
    ramp_n = nt.nodes.new("ShaderNodeMapRange")
    ramp_n.inputs["To Min"].default_value = 0.955
    ramp_n.inputs["To Max"].default_value = 1.025
    nt.links.new(lump.outputs["Fac"], ramp_n.inputs["Value"])
    comb = nt.nodes.new("ShaderNodeCombineColor")
    for s in ("Red", "Green", "Blue"):
        nt.links.new(ramp_n.outputs["Result"], comb.inputs[s])
    nt.links.new(comb.outputs["Color"], mix.inputs[7])
    # tight contact occlusion where things meet: what makes objects sit
    ao = nt.nodes.new("ShaderNodeAmbientOcclusion")
    ao.inputs["Distance"].default_value = 0.07
    ao.samples = 8
    aor = nt.nodes.new("ShaderNodeMapRange")
    aor.inputs["To Min"].default_value = 0.58
    aor.inputs["To Max"].default_value = 1.0
    nt.links.new(ao.outputs["AO"], aor.inputs["Value"])
    aom = nt.nodes.new("ShaderNodeMix")
    aom.data_type = "RGBA"
    aom.blend_type = "MULTIPLY"
    aom.inputs["Factor"].default_value = 1.0
    nt.links.new(mix.outputs[2], aom.inputs[6])
    acomb = nt.nodes.new("ShaderNodeCombineColor")
    for s_ in ("Red", "Green", "Blue"):
        nt.links.new(aor.outputs["Result"], acomb.inputs[s_])
    nt.links.new(acomb.outputs["Color"], aom.inputs[7])
    nt.links.new(aom.outputs[2], bsdf.inputs["Base Color"])
    nt.links.new(bsdf.outputs["BSDF"], out.inputs["Surface"])
    if LOOK["name"] == "v2":
        clay_v2(nt, bsdf, tc, fine, b1, b2, mix, aor, aom, acomb, bump)
    _mats[name] = m
    return m


def clay_v2(nt, bsdf, tc, fine, b1, b2, mix, aor, aom, acomb, bump):
    """The v2 skin on top of the v1 graph, so v1 renders stay byte-identical.

    Set by eye on the before/after crop of frame 200 (docs/INTENT-home.md,
    "the clay look"), never fitted to Clay's pixels: synthesising their look,
    not cloning it, is the brief. Treat each as guessed, then judged."""
    # Subsurface: 0.04 read as painted plastic. 0.22 at a 2cm radius lets the
    # key glow through thin edges, which is most of what makes clay read as
    # clay at this scale (the parts are 0.1 to 0.5 units, one unit a metre).
    bsdf.inputs["Subsurface Weight"].default_value = 0.22
    bsdf.inputs["Subsurface Radius"].default_value = (1.0, 0.45, 0.28)
    bsdf.inputs["Subsurface Scale"].default_value = 0.02
    bsdf.inputs["Roughness"].default_value = min(bsdf.inputs["Roughness"].default_value, 0.52)
    bsdf.inputs["Specular IOR Level"].default_value = 0.4
    # a velvet rim, the soft bright edge a matte clay surface shows at grazing angles
    bsdf.inputs["Sheen Weight"].default_value = 0.3
    bsdf.inputs["Sheen Roughness"].default_value = 0.45
    # Grain you can see: the fine noise twice as fine and nearly twice as
    # strong, plus thumb-pressed dimples from a Voronoi layer.
    fine.inputs["Scale"].default_value = 260.0
    fine.inputs["Detail"].default_value = 6.0
    b1.inputs["Strength"].default_value = 0.18 * bump
    vor = nt.nodes.new("ShaderNodeTexVoronoi")
    vor.feature = "SMOOTH_F1"
    vor.inputs["Scale"].default_value = 38.0
    nt.links.new(tc.outputs["Object"], vor.inputs["Vector"])
    b3 = nt.nodes.new("ShaderNodeBump")
    b3.inputs["Strength"].default_value = 0.07 * bump
    b3.inputs["Distance"].default_value = 0.004
    nt.links.new(vor.outputs["Distance"], b3.inputs["Height"])
    nt.links.new(b2.outputs["Normal"], b3.inputs["Normal"])
    nt.links.new(b3.outputs["Normal"], bsdf.inputs["Normal"])
    # Saturation up 25% before occlusion (v1 frame mean 0.089).
    hsv = nt.nodes.new("ShaderNodeHueSaturation")
    hsv.inputs["Saturation"].default_value = 1.25
    nt.links.new(mix.outputs[2], hsv.inputs["Color"])
    nt.links.new(hsv.outputs["Color"], aom.inputs[6])
    # Warm occlusion: creases go to a terracotta brown, never grey. The v1
    # grey multiply is what made every contact read as dust.
    warm = nt.nodes.new("ShaderNodeValToRGB")
    warm.color_ramp.elements[0].position = 0.0
    warm.color_ramp.elements[0].color = (0.30, 0.13, 0.08, 1.0)
    warm.color_ramp.elements[1].position = 1.0
    warm.color_ramp.elements[1].color = (1.0, 1.0, 1.0, 1.0)
    aor.inputs["To Min"].default_value = 0.35
    nt.links.new(aor.outputs["Result"], warm.inputs["Fac"])
    nt.links.new(warm.outputs["Color"], aom.inputs[7])


def reskin(ob):
    """Nalana parts arrive with their own Principled setups. Re-skin them with
    the house clay so every object shares one material language, and push any
    green to lilac (the one secondary) and any orange to gold."""
    if ob.type not in {"MESH", "CURVE"}:
        return
    data = ob.data
    for i, slot in enumerate(data.materials):
        col = (0.8, 0.8, 0.8, 1.0)
        if slot and slot.use_nodes:
            for n in slot.node_tree.nodes:
                if n.type == "BSDF_PRINCIPLED":
                    col = tuple(n.inputs["Base Color"].default_value)
                    break
        elif slot:
            col = tuple(slot.diffuse_color)
        r, g, b = col[:3]
        if g > r * 1.05 and g > b * 1.05:
            key, c = "lilac", None
        elif r > g * 1.25 and g > b * 1.6 and r > 0.3:
            key, c = "gold", None
        else:
            key = "n_%02x%02x%02x" % tuple(int(255 * max(0, min(1, v)) ** (1 / 2.2)) for v in (r, g, b))
            c = col
        data.materials[i] = clay(key, c)
    if ob.type == "CURVE" and not data.materials:
        data.materials.append(clay("ink"))


