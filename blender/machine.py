def grain_image(size=512, seed=5):
    """Gaussian grain tile written to disk and loaded back: a generated,
    packed float image reached the compositor as black on Blender 5.2."""
    import tempfile
    path = os.path.join(tempfile.gettempdir(), f"tts_grain_{size}_{seed}.png")
    if not os.path.exists(path):
        rng = np.random.default_rng(seed)
        g = rng.normal(0.5, 0.17, (size, size)).clip(0, 1).astype(np.float32)
        tmp = bpy.data.images.new("grain_src", size, size)
        tmp.pixels.foreach_set(np.stack([g, g, g, np.ones_like(g)], axis=-1).ravel())
        tmp.filepath_raw = path
        tmp.file_format = "PNG"
        tmp.save()
        bpy.data.images.remove(tmp)
    img = bpy.data.images.load(path, check_existing=True)
    img.colorspace_settings.name = "Non-Color"
    return img


def setup_render(res_x, res_y, samples, threshold=0.02, grain=True):
    sc = bpy.context.scene
    # Pixel sizes below were tuned at 1600 wide; scale them with the frame so
    # the 2560 cut has the same soft edges, not edges 1.6 times harder.
    k = max(res_x, res_y) / 1600
    # The scene does not change topology between frames: keep the BVH and
    # the textures across the sequence instead of rebuilding them per frame.
    sc.render.use_persistent_data = True
    sc.render.engine = "CYCLES"
    prefs = bpy.context.preferences.addons["cycles"].preferences
    prefs.compute_device_type = "METAL"
    prefs.get_devices()
    for d in prefs.devices:
        d.use = d.type == "METAL"
    sc.cycles.device = "GPU"
    sc.cycles.samples = samples
    sc.cycles.use_adaptive_sampling = True
    sc.cycles.adaptive_threshold = threshold
    sc.cycles.use_denoising = True
    # OIDN on the GPU: on the CPU it fought every other job on the machine.
    if hasattr(sc.cycles, "denoising_use_gpu"):
        sc.cycles.denoising_use_gpu = True
    sc.cycles.max_bounces = 8
    sc.cycles.diffuse_bounces = 4
    sc.cycles.glossy_bounces = 3
    sc.cycles.sample_clamp_indirect = 4.0
    sc.render.resolution_x = res_x
    sc.render.resolution_y = res_y
    sc.render.resolution_percentage = 100
    sc.render.fps = FPS
    sc.frame_start, sc.frame_end = 1, FRAMES
    sc.render.film_transparent = False
    try:
        sc.view_settings.view_transform = _VIEW["view"]
        if _VIEW["look"] != "None":
            sc.view_settings.look = _VIEW["look"]
    except TypeError:
        sc.view_settings.view_transform = "Filmic"
    sc.view_settings.exposure = _VIEW["exposure"]
    sc.render.image_settings.file_format = "PNG"
    sc.render.image_settings.color_mode = "RGB"
    # film grain in the compositor, shifted every frame so it reads as film, not dirt
    ng = bpy.data.node_groups.new("Grain", "CompositorNodeTree")
    sc.compositing_node_group = ng
    ng.interface.new_socket("Image", in_out="OUTPUT", socket_type="NodeSocketColor")
    rl = ng.nodes.new("CompositorNodeRLayers")
    out = ng.nodes.new("NodeGroupOutput")
    gi = ng.nodes.new("CompositorNodeImage")
    gi.image = grain_image()
    tr = ng.nodes.new("CompositorNodeTranslate")
    for key in ("wrap_axis",):
        if hasattr(tr, key):
            setattr(tr, key, "BOTH")
    try:
        tr.inputs["Extension X"].default_value = "Repeat"
        tr.inputs["Extension Y"].default_value = "Repeat"
    except (KeyError, TypeError):
        pass
    # grain scales with the pixel (a * (1 + f * (g - 0.5))), so saturated and
    # dark objects get the same relative grain as the ground. Additive grain
    # turned the gold cube to sandpaper in lookdev v11.
    lift = ng.nodes.new("ShaderNodeMix")
    lift.data_type = "RGBA"
    lift.blend_type = "ADD"
    lift.inputs["Factor"].default_value = 1.0
    lift.inputs[7].default_value = (0.5, 0.5, 0.5, 1.0)
    mix = ng.nodes.new("ShaderNodeMix")
    mix.data_type = "RGBA"
    mix.blend_type = "MULTIPLY"
    # f = 0.26 with nearest sampling: ground std close to Clay's measured 0.026
    # --no-grain leaves it to the page: per-pixel grain in every frame of a
    # 2560 sequence tripled its WebP size, and the page draws the same grain
    # live at the screen's own pixels.
    mix.inputs["Factor"].default_value = 0.26 if grain else 0.0
    ng.links.new(gi.outputs["Image"], tr.inputs["Image"])
    ng.links.new(tr.outputs["Image"], lift.inputs[6])
    # bookends: frame 1 is a flat field of the ground colour (#F4EFE6) that the
    # page crossfades into; the last frames brighten to it at the edges
    fade = ng.nodes.new("ShaderNodeMix")
    fade.data_type = "RGBA"
    fade.blend_type = "MIX"
    fade.inputs[7].default_value = hexcol("ground")
    ell2 = ng.nodes.new("CompositorNodeEllipseMask")
    for key, val in (("Size", (0.62, 0.62)),):
        if key in ell2.inputs:
            ell2.inputs[key].default_value = val
    blur2 = ng.nodes.new("CompositorNodeBlur")
    if "Size" in blur2.inputs:
        blur2.inputs["Size"].default_value = (260 * k, 260 * k)
    ng.links.new(ell2.outputs[0], blur2.inputs[0])
    inv = ng.nodes.new("ShaderNodeMath")
    inv.operation = "SUBTRACT"
    inv.inputs[0].default_value = 1.0
    ng.links.new(blur2.outputs[0], inv.inputs[1])
    edge = ng.nodes.new("ShaderNodeMath")
    edge.name = "EdgeFade"
    edge.operation = "MULTIPLY"
    ng.links.new(inv.outputs[0], edge.inputs[0])
    full = ng.nodes.new("ShaderNodeMath")
    full.name = "FullFade"
    full.operation = "MAXIMUM"
    ng.links.new(edge.outputs[0], full.inputs[0])
    ng.links.new(full.outputs[0], fade.inputs["Factor"])
    ng.links.new(rl.outputs["Image"], fade.inputs[6])
    ng.links.new(fade.outputs[2], mix.inputs[6])
    ts = frame_times()
    end_t = ts[-1]
    full_v = [1.0 - smoother((t - T0 - 0.15) / 0.6) for t in ts]
    edge_v = [smoother((t - (end_t - 1.0)) / 0.9) for t in ts]
    fcurve_bake(ng, 'nodes["FullFade"].inputs[1].default_value', [full_v])
    fcurve_bake(ng, 'nodes["EdgeFade"].inputs[1].default_value', [edge_v])
    _BOOKEND["vig"] = [0.86 + 0.14 * max(fv, ev) for fv, ev in zip(full_v, edge_v)]
    ng.links.new(lift.outputs[2], mix.inputs[7])
    # gentle vignette: a soft ellipse, edges down to about 86%
    try:
        ell = ng.nodes.new("CompositorNodeEllipseMask")
        for key, val in (("Size", (0.95, 0.95)), ("Width", 0.95), ("Height", 0.95)):
            if key in ell.inputs:
                ell.inputs[key].default_value = val
        blur = ng.nodes.new("CompositorNodeBlur")
        for key, val in (("Size", (300 * k, 300 * k)),):
            if key in blur.inputs:
                blur.inputs[key].default_value = val
        ng.links.new(ell.outputs[0], blur.inputs[0])
        mr = ng.nodes.new("ShaderNodeMapRange")
        mr.name = "Vignette"
        mr.inputs["To Min"].default_value = 0.86
        fcurve_bake(ng, 'nodes["Vignette"].inputs[3].default_value', [_BOOKEND["vig"]])
        mr.inputs["To Max"].default_value = 1.0
        ng.links.new(blur.outputs[0], mr.inputs["Value"])
        vig = ng.nodes.new("ShaderNodeMix")
        vig.data_type = "RGBA"
        vig.blend_type = "MULTIPLY"
        vig.inputs["Factor"].default_value = 1.0
        ng.links.new(mix.outputs[2], vig.inputs[6])
        ng.links.new(mr.outputs["Result"], vig.inputs[7])
        ng.links.new(vig.outputs[2], out.inputs[0])
    except Exception as exc:
        print("vignette skipped:", exc)
        ng.links.new(mix.outputs[2], out.inputs[0])
    rng = random.Random(1)
    # whole-pixel offsets and nearest sampling: a fractional shift blurred the
    # grain to 40% of its strength
    try:
        tr.inputs["Interpolation"].default_value = "Nearest"
    except (KeyError, TypeError):
        pass
    xs = [float(rng.randint(-256, 256)) for _ in range(FRAMES)]
    ys = [float(rng.randint(-256, 256)) for _ in range(FRAMES)]
    try:
        fcurve_bake(ng, 'nodes["%s"].inputs[1].default_value' % tr.name, [xs])
        fcurve_bake(ng, 'nodes["%s"].inputs[2].default_value' % tr.name, [ys])
    except Exception as exc:
        print("grain offset not animated:", exc)


def main():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", default="check", choices=["check", "stills", "frames", "save"])
    ap.add_argument("--out", default="/tmp/machine")
    ap.add_argument("--frames", default="1-300")
    ap.add_argument("--portrait", action="store_true")
    ap.add_argument("--res", type=int, default=0, help="width override for previews")
    ap.add_argument("--samples", type=int, default=32)
    ap.add_argument("--threshold", type=float, default=0.03)
    ap.add_argument("--stills", default="1,40,75,110,140,170,200,225,250,300")
    ap.add_argument("--skip-audit", action="store_true")
    ap.add_argument("--no-grain", action="store_true")
    ap.add_argument("--stages", default="", help="write stage frame ranges as JSON here")
    ap.add_argument("--look", default="v1", choices=["v1", "v2"],
                    help="v1 reproduces the shipped /way film; v2 is the clay look")
    ap.add_argument("--region", default="", help="render border x0,y0,x1,y1 in 0..1, for crops")
    a = ap.parse_args(argv)
    LOOK["name"] = a.look
    m, show = build_and_bake()
    if not a.skip_audit:
        audit(m, show)
    if a.stages:
        import json
        with open(a.stages, "w") as fh:
            json.dump(show.stage_frames(), fh)
        print("STAGES", show.stage_frames())
    if a.mode == "check":
        return
    build_camera(m, show, portrait=a.portrait)
    w, h = (720, 1280) if a.portrait else (1600, 900)
    if a.res:
        h = int(round(h * a.res / w / 2) * 2)
        w = a.res
    setup_render(w, h, a.samples, a.threshold, grain=not a.no_grain)
    os.makedirs(a.out, exist_ok=True)
    sc = bpy.context.scene
    if a.mode == "save":
        bpy.ops.wm.save_as_mainfile(filepath=os.path.join(a.out, "machine.blend"))
        return
    if a.mode == "stills":
        frames = [int(x) for x in a.stills.split(",")]
    else:
        lo, hi = (int(x) for x in a.frames.split("-"))
        frames = list(range(lo, hi + 1))
    if a.region:
        x0, y0, x1, y1 = (float(v) for v in a.region.split(","))
        sc.render.use_border = True
        sc.render.use_crop_to_border = True
        sc.render.border_min_x, sc.render.border_min_y = x0, y0
        sc.render.border_max_x, sc.render.border_max_y = x1, y1
    for f in frames:
        sc.frame_set(f)
        sc.render.filepath = os.path.join(a.out, f"f{f:04d}.png")
        bpy.ops.render.render(write_still=True)


if __name__ == "__main__":
    main()
